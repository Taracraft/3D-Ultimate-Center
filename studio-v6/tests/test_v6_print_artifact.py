def test_upload_accepts_data_channel_timeout_after_verified_remote_size(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    data = artifact()

    class TimeoutClient:
        closed = False

        def storbinary(
            self,
            command: str,
            stream: io.BytesIO,
            blocksize: int,
        ) -> None:
            assert command == "STOR beta1.gcode.3mf"
            assert blocksize == 256 * 1024
            assert stream.read() == data
            raise TimeoutError("TLS close-notify missing")

        def close(self) -> None:
            self.closed = True

        def quit(self) -> None:
            raise AssertionError(
                "Timeout connections must be closed without QUIT",
            )

    client = TimeoutClient()
    monkeypatch.setattr(
        print_artifact,
        "_connect_ftps",
        lambda **_kwargs: client,
    )
    monkeypatch.setattr(
        print_artifact,
        "_remote_file_size",
        lambda **_kwargs: len(data),
    )

    result = print_artifact.upload_gcode_3mf(
        host="printer.local",
        access_code="secret",
        printer_id="SERIAL",
        filename="beta1.3mf",
        data=data,
        tls_insecure=True,
    )

    assert client.closed is True
    assert result.size_bytes == len(data)
    assert result.remote_filename == "beta1.gcode.3mf"
    assert result.remote_url == "ftp:///beta1.gcode.3mf"
    assert result.validation_report["line_count"] >= 100


