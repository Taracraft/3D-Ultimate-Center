def rendered_gcode() -> bytes:
    lines = [
        "; generated by Bambu Studio",
        "; complete rendered V6 regression artifact",
        "M1002 gcode_claim_action : 1",
        "G392 S0",
        "M104 S220",
        "M140 S60",
        "M109 S220",
        "M190 S60",
        "M620 S0A",
        "M621 S0A",
        "M1002 judge_flag g29_before_print_flag",
        "G29 A1",
        "M1002 judge_flag extrude_cali_flag",
        "M983 A0",
        "; WIPE NOZZLE",
        "M900 C",
    ]
    lines.extend(f"G1 X{index} Y1 E0.10" for index in range(1, 96))
    lines.extend(["M104 S0", "M140 S0"])
    return ("\n".join(lines) + "\n").encode("utf-8")


def artifact(*, with_preview: bool = False) -> bytes:
    target = io.BytesIO()
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("Metadata/plate_1.gcode", rendered_gcode())
        if with_preview:
            archive.writestr("Metadata/plate_1.png", b"PNG")
            archive.writestr("Metadata/plate_1_small.png", b"PNG")
    return target.getvalue()


def uploaded():
    validated = print_artifact.validate_gcode_3mf("beta1.3mf", artifact())
    return print_artifact.UploadedPrintArtifact(
        printer_id="SERIAL",
        remote_filename="beta1.gcode.3mf",
        remote_url="ftp:///beta1.gcode.3mf",
        size_bytes=100,
        sha256="a" * 64,
        gcode_path="Metadata/plate_1.gcode",
        validation_report=validated.validation_report,
    )


def test_valid_single_plate_artifact() -> None:
    data = artifact(with_preview=True)
    result = print_artifact.validate_gcode_3mf("beta1.3mf", data)
    assert result.filename == "beta1.gcode.3mf"
    assert result.gcode_path == "Metadata/plate_1.gcode"
    assert result.size_bytes == len(data)
    assert len(result.sha256) == 64
    assert result.validation_report["line_count"] >= 100
    assert result.validation_report["extrusion_moves"] >= 5
    assert result.validation_report["display_preview_available"] is True
    assert result.validation_report["preview_paths"] == [
        "Metadata/plate_1.png",
        "Metadata/plate_1_small.png",
    ]


