def sample_gcode(*, object_name: str = "") -> bytes:
    lines = [
        "; generated by Bambu Studio",
        *([f"; object name: {object_name}"] if object_name else []),
        "G90",
        "M82",
        "G92 E0",
        "G1 X10 Y10 F6000",
        "G1 X60 Y10 E2.0 F1200",
        "G1 X60 Y50 E4.0",
        "G1 X10 Y50 E6.0",
        "G1 X10 Y10 E8.0",
    ]
    return ("\n".join(lines) + "\n").encode()


def source_3mf(*names: str) -> bytes:
    objects = "".join(
        (
            f'<object id="{index}" type="model" name="{name}">'
            '<mesh><vertices>'
            '<vertex x="0" y="0" z="0"/>'
            '<vertex x="1" y="0" z="0"/>'
            '<vertex x="0" y="1" z="0"/>'
            '</vertices><triangles>'
            '<triangle v1="0" v2="1" v3="2"/>'
            '</triangles></mesh></object>'
        )
        for index, name in enumerate(names, start=1)
    )
    model = (
        '<?xml version="1.0" encoding="UTF-8"?>'
        '<model unit="millimeter" '
        'xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">'
        '<metadata name="Title">Druckplatte 1</metadata>'
        f'<resources>{objects}</resources>'
        '<build><item objectid="1"/></build>'
        '</model>'
    ).encode()
    target = BytesIO()
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("3D/3dmodel.model", model)
    return target.getvalue()


def native_sliced_3mf() -> tuple[bytes, bytes, dict[str, bytes]]:
    gcode = sample_gcode(object_name="Brause Quadrat 25")
    preserved = {
        "3D/3dmodel.model": b"native-model",
        "Metadata/plate_1.json": b'{"plate_index":1,"native":true}',
        "Metadata/project_settings.config": b'{"printer_model":"A1"}',
        "Metadata/model_settings.config": b"native-model-settings",
        "Metadata/slice_info.config": b"native-slice-info",
        "Metadata/plate_1.gcode.md5": b"0123456789abcdef0123456789abcdef",
        "_rels/.rels": b"native-relations",
    }
    content_types = (
        '<?xml version="1.0" encoding="UTF-8"?>'
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
        '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
        '<Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/>'
        '<Default Extension="config" ContentType="application/octet-stream"/>'
        '<Default Extension="gcode" ContentType="text/x.gcode"/>'
        '<Default Extension="json" ContentType="application/json"/>'
        '</Types>'
    ).encode()
    target = BytesIO()
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("[Content_Types].xml", content_types)
        for name, value in preserved.items():
            archive.writestr(name, value)
        archive.writestr("Metadata/plate_1.gcode", gcode)
    return target.getvalue(), gcode, preserved


