def test_display_ready_archive_contains_exact_gcode_and_thumbnails() -> None:
    gcode = sample_gcode()
    content, filename, digest = module.build_bambu_project_archive(
        "Brause Quadrat",
        gcode,
        "fallback",
    )
    assert filename == "Brause Quadrat.gcode.3mf"
    assert len(digest) == 64

    with zipfile.ZipFile(BytesIO(content)) as archive:
        names = set(archive.namelist())
        assert "Metadata/plate_1.gcode" in names
        assert "Metadata/plate_1.png" in names
        assert "Metadata/plate_1_small.png" in names
        assert "Metadata/plate_no_light_1.png" in names
        assert "Metadata/pick_1.png" in names
        assert archive.read("Metadata/plate_1.gcode") == gcode
        large = archive.read("Metadata/plate_1.png")
        small = archive.read("Metadata/plate_1_small.png")

    assert large.startswith(b"\x89PNG\r\n\x1a\n")
    assert small.startswith(b"\x89PNG\r\n\x1a\n")
    assert struct.unpack(">II", large[16:24]) == (512, 512)
    assert struct.unpack(">II", small[16:24]) == (128, 128)
    assert len(large) > 200


def test_native_bambu_archive_preserves_metadata_and_adds_previews() -> None:
    native, gcode, preserved = native_sliced_3mf()
    content, filename, digest = module.prepare_bambu_project_artifact(
        "Brause Quadrat 25",
        native,
        "fallback",
    )

    assert filename == "Brause Quadrat 25.gcode.3mf"
    assert len(digest) == 64
    assert module.gcode_from_bambu_project_artifact(content) == gcode

    with zipfile.ZipFile(BytesIO(content)) as archive:
        names = set(archive.namelist())
        for name, value in preserved.items():
            assert archive.read(name) == value
        assert archive.read("Metadata/plate_1.gcode") == gcode
        for preview in (
            "Metadata/plate_1.png",
            "Metadata/plate_1_small.png",
            "Metadata/plate_no_light_1.png",
            "Metadata/pick_1.png",
        ):
            assert preview in names
            assert archive.read(preview).startswith(b"\x89PNG\r\n\x1a\n")

        content_types = ET.fromstring(archive.read("[Content_Types].xml"))
        extensions = {
            str(item.attrib.get("Extension") or "").casefold()
            for item in content_types
        }
        assert "png" in extensions


def test_native_gcode_extraction_rejects_multiple_plate_gcodes() -> None:
    target = BytesIO()
    with zipfile.ZipFile(target, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("Metadata/plate_1.gcode", sample_gcode())
        archive.writestr("Metadata/plate_2.gcode", sample_gcode())
    try:
        module.gcode_from_bambu_project_artifact(target.getvalue())
    except ValueError as exc:
        assert "genau eine" in str(exc)
    else:
        raise AssertionError("Multiple native G-code entries were accepted")


